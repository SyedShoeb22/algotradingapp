
import streamlit as st
import pandas as pd
import plotly.express as px
import os

st.set_page_config(
    page_title="Algo Trading Backtest",
    page_icon="📈",
    layout="wide"
)

st.title("SBIN-EQ Strategy Backtesting Dashboard")
st.caption("Historical simulation | Paper trading only")

trades_path = "data/backtest_trades.csv"
equity_path = "data/backtest_equity.csv"

if not os.path.exists(trades_path) or not os.path.exists(equity_path):
    st.error("Backtest files not found. Run the backtest first.")
    st.stop()

trades = pd.read_csv(trades_path)
equity = pd.read_csv(equity_path)

if equity.empty:
    st.warning("No equity data available.")
    st.stop()

equity["time"] = pd.to_datetime(equity["time"])

initial_capital = 100000.0
final_capital = float(equity.iloc[-1]["equity"])
net_profit = final_capital - initial_capital

total_trades = len(trades)

if total_trades:
    winning_trades = int((trades["net_pnl"] > 0).sum())
    win_rate = winning_trades / total_trades * 100
else:
    winning_trades = 0
    win_rate = 0.0

max_drawdown = float(
    equity["drawdown_pct"].min()
)

st.subheader("Performance Overview")

c1, c2, c3, c4 = st.columns(4)

c1.metric("Final Capital", f"₹{final_capital:,.2f}")
c2.metric(
    "Net Profit / Loss",
    f"₹{net_profit:,.2f}",
    f"{net_profit / initial_capital * 100:.2f}%"
)
c3.metric("Total Trades", total_trades)
c4.metric("Win Rate", f"{win_rate:.2f}%")

st.divider()

st.subheader("Portfolio Equity Curve")

fig = px.line(
    equity,
    x="time",
    y="equity",
    title="Portfolio Value Over Time",
    labels={
        "time": "Time",
        "equity": "Portfolio Value (₹)"
    }
)

st.plotly_chart(fig, use_container_width=True)

st.subheader("Drawdown")

drawdown_fig = px.area(
    equity,
    x="time",
    y="drawdown_pct",
    title="Portfolio Drawdown (%)"
)

st.plotly_chart(drawdown_fig, use_container_width=True)

st.subheader("Trade History")

if not trades.empty:
    st.dataframe(
        trades,
        use_container_width=True,
        hide_index=True
    )

    st.download_button(
        "Download Trade History",
        trades.to_csv(index=False),
        file_name="backtest_trades.csv",
        mime="text/csv"
    )
else:
    st.info("No trades were generated by this strategy.")

st.subheader("Risk Summary")

st.write("Maximum drawdown:", f"{abs(max_drawdown):.2f}%")
st.write("Winning trades:", winning_trades)
st.write("Losing trades:", total_trades - winning_trades)

st.warning(
    "Historical backtest results do not guarantee future performance. "
    "This dashboard does not execute real trades."
)

